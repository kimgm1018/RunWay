#!/usr/bin/env bash
# 복구에 필요한 공개 설정만 기록한다. DB 접속 정보·HF 토큰은 이 목록에 넣지 않는다.
PUBLIC_KEYS=(
    ODEV21_CHECKPOINT_PATH ODEV21_CHECKPOINT_SHA256
    ODEV21_SUMMARY_STATS_PATH ODEV21_SUMMARY_STATS_SHA256
    ODEV21_POPULATION_BUNDLE_PATH ODEV21_POPULATION_BUNDLE_SHA256
    ODEV21_VARIANT ODEV21_DEVICE ODEV21_TORCH_THREADS ODEV21_WARMUP_ENABLED
    ODEV21_VALIDATED_HORIZON_SEC ODEV21_VALIDATION_REF ODEV21_P4_LR ODEV21_P4_LAMBDA ODEV21_P4_STEPS
    ODEV21_P4_WARM_START ODEV21_P4_WARM_STEPS ODEV21_P4_EARLY_STOP_TOL
    PERSONAL_PLAN_POPULATION_MODE PERSONAL_PLAN_EXPERIMENTAL_ENABLED
    PERSONAL_PLAN_SEARCH_BUDGET_CELLS PLAN_FIRST_SEGMENT_NO_FASTER_THAN_MEAN
    ODE_PREVIEW_ENABLED DECIDE_FORECAST_ENABLED FREE_RUN_GRADE_POLICY MPC_MARGIN_TABLE_PATH
    GRU_PERSONALIZATION_ENABLED GRU_PERSONALIZATION_MAX_WINDOWS GRU_PERSONALIZATION_CACHE_TTL_SEC
    GRU_PERSONALIZATION_EMPTY_CACHE_TTL_SEC GRU_PERSONALIZATION_CACHE_MAX_USERS GRU_PERSONALIZATION_DB_TIMEOUT_MS
    HEAVY_MAX_CONCURRENCY HEAVY_PERSONALIZE_MAX_CONCURRENCY HEAVY_QUEUE_WAIT_SEC
)

write_settings() {
    local output=$1 key value
    shift
    : > "$output"
    for key in "${PUBLIC_KEYS[@]}"; do
        if (( $# > 0 )); then
            value=$1; shift
        elif [[ -v $key ]]; then
            value=${!key}
        else
            # 미지정 값은 앱의 기본값을 유지한다. 빈 문자열로 강제하지 않는다.
            printf 'unset %s\n' "$key" >> "$output"
            continue
        fi
        printf 'export %s=%q\n' "$key" "$value" >> "$output"
    done
}
